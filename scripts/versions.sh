# opusfile reads an .opus file; libopus alone only decodes packets.
#
# The odd one out, and the only dependency here that is not a release. Xiph
# has published no opusfile release since 0.12 in 2020, and 0.12 builds with
# autotools only, which nothing else here uses and which cannot follow the
# CMake toolchain files the cross targets are built with. CMake support
# landed upstream after 0.12, so this is a commit from Xiph's own repository
# rather than a fork: the tree that "git describe" calls v0.12-59-g6dfd29e.
# SDL_mixer makes the same choice, vendoring a post-0.12 snapshot of its own.
#
# A GitHub commit archive is not promised to be byte for byte stable, so this
# checksum may one day stop matching a fresh download even though the commit
# has not changed. That breaks nothing: the archive is in git and no build
# reaches the network. It would mean re-checking the contents by hand before
# recording a new hash.
#
# THIRD_PARTY_NOTICES.md, "opusfile is pinned to a commit, not a release", has
# the rest: what was checked before accepting it, and what to do if Xiph ever
# publishes a release that ships a CMakeLists.txt.
OPUSFILE_VERSION=0.12-59-g6dfd29e
