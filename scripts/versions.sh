# The audio codecs, all built before SDL_mixer, which links them.
#
# Four of the five formats SDL_mixer can decode have two decoders: a small
# single file one bundled inside SDL_mixer, and the format author's own
# library. These are the authors' own, and SDL_mixer is built against them
# rather than against the bundled copies. They decode more of each format,
# they are the code every other player uses, and a security advisory against
# one of them is published rather than left for somebody to notice.
#
# Opus and WavPack have no bundled decoder at all, so they are formats the
# toolkit could not play before.
#
# Every one of these is BSD style. THIRD_PARTY_NOTICES.md records each.
#
# Build order: libogg first, since Vorbis, FLAC and Opus all store their
# packets in Ogg containers and every one of the three looks for it.
